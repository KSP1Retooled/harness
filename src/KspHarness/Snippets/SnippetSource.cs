using System.Text;

namespace KspHarness.Snippets;

internal enum SnippetForm
{
    /// <summary>A method body that returns the result.</summary>
    BodyWithReturn,

    /// <summary>A method body with no result.</summary>
    BodyWithoutReturn,

    /// <summary>A lambda with no parameters, invoked through the overloads that pick its natural delegate type.</summary>
    Lambda,
}

/// <summary>A variable the snippet reads from the test: declared as a local and passed as an argument.</summary>
internal sealed record Capture(string Name, string TypeSyntax, object? Value);

/// <summary>Where the user's code starts in the test's source file; Line and Column are 1-based.</summary>
internal sealed record SourcePosition(string? File, int Line, int Column)
{
    public static SourcePosition Unknown { get; } = new(null, 1, 1);
}

/// <summary>Everything that decides a snippet's generated source.</summary>
internal sealed record SnippetSource(
    SnippetForm Form,
    string Code,
    IReadOnlyList<Capture> Captures,
    IReadOnlyList<string> Usings,
    SourcePosition Position
)
{
    public const string Namespace = "KspHarness.Snippets";

    public const string MethodName = "Run";

    public const string HashPlaceholder = "__SNIPPET_HASH__";

    private static readonly string[] StandardUsings =
    [
        "System",
        "System.Collections.Generic",
        "System.Linq",
        "System.Threading.Tasks",
        "UnityEngine",
        "KSP.UI.Screens",
        "KspHarness.Script",
    ];

    public static string ClassName(string hash) => "S_" + hash[..16];

    /// <summary>The generated source with <see cref="HashPlaceholder"/> where the class name's hash goes.</summary>
    public string Generate()
    {
        var source = new StringBuilder();
        source.Append("// <auto-generated/>\n");
        source.Append("#nullable disable\n");
        foreach (var name in StandardUsings.Concat(Usings).Distinct())
        {
            source.Append(UsingLine(name)).Append('\n');
        }

        // Both namespaces above declare these; snippets mean Unity's.
        source.Append("using Object = UnityEngine.Object;\n");
        source.Append("using Random = UnityEngine.Random;\n");
        source.Append('\n');
        source.Append($"namespace {Namespace}\n");
        source.Append("{\n");
        source.Append($"    public static class S_{HashPlaceholder}\n");
        source.Append("    {\n");
        source.Append($"        public static async Task<object> {MethodName}(object[] __args)\n");
        source.Append("        {\n");

        for (var i = 0; i < Captures.Count; i++)
        {
            var capture = Captures[i];
            source.Append(
                $"            {capture.TypeSyntax} {capture.Name} = Args.Get<{capture.TypeSyntax}>(__args, {i});\n"
            );
        }

        var code = Code.ReplaceLineEndings("\n");
        switch (Form)
        {
            case SnippetForm.BodyWithReturn:
                AppendMapped(source, code, padFirstLine: false);
                break;
            case SnippetForm.BodyWithoutReturn:
                source.Append("            async Task __body()\n");
                source.Append("            {\n");
                AppendMapped(source, code, padFirstLine: false);
                source.Append("            }\n");
                source.Append("            await __body();\n");
                source.Append("            return null;\n");
                break;
            case SnippetForm.Lambda:
                source.Append("            return await __Lambda.Invoke(\n");
                AppendMapped(source, code, padFirstLine: true);
                source.Append("            );\n");
                break;
        }

        source.Append("        }\n");
        source.Append("    }\n");

        if (Form == SnippetForm.Lambda)
        {
            source.Append(LambdaInvoker);
        }

        source.Append("}\n");
        return source.ToString();
    }

    private void AppendMapped(StringBuilder source, string code, bool padFirstLine)
    {
        if (Position.File is not null)
        {
            source.Append($"#line {Position.Line} \"{Position.File}\"\n");
        }

        // Padding the first line to the column where the code starts in the test keeps reported columns exact.
        if (padFirstLine && Position.File is not null && Position.Column > 1)
        {
            source.Append(' ', Position.Column - 1);
        }

        source.Append(code);
        if (!code.EndsWith('\n'))
        {
            source.Append('\n');
        }

        if (Position.File is not null)
        {
            source.Append("#line default\n");
        }
    }

    private static string UsingLine(string name)
    {
        var trimmed = name.Trim().TrimEnd(';');
        return trimmed.StartsWith("using ", StringComparison.Ordinal) ? trimmed + ";" : $"using {trimmed};";
    }

    // Overload resolution over these picks the lambda's natural shape, as it does for Task.Run: an async lambda with
    // or without a result, a value, or a statement.
    private const string LambdaInvoker = """

            internal static class __Lambda
            {
                public static async Task<object> Invoke<T>(Func<Task<T>> body)
                {
                    return await body();
                }

                public static async Task<object> Invoke(Func<Task> body)
                {
                    await body();
                    return null;
                }

                public static Task<object> Invoke<T>(Func<T> body)
                {
                    return Task.FromResult<object>(body());
                }

                public static Task<object> Invoke(Action body)
                {
                    body();
                    return Task.FromResult<object>(null);
                }
            }

        """;
}
